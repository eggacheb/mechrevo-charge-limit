# -*- coding: utf-8 -*-
"""安装 / 卸载开机自启（当前用户启动文件夹放一个静默 VBS 启动器）。

用法：
    python install_autostart.py            # 安装
    python install_autostart.py --remove   # 卸载
    python install_autostart.py --status   # 查看状态

VBS 内容刻意保持纯 ASCII —— WScript 按系统 ANSI 代码页读取，
混入 UTF-8 中文注释会导致解析异常。
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GUARD = os.path.join(HERE, "pin_guard.py")
STARTUP = os.path.join(os.environ.get("APPDATA", ""),
                       "Microsoft", "Windows", "Start Menu", "Programs", "Startup")
LINK_NAME = "MechrevoChargeLimit-guard.vbs"
LINK_PATH = os.path.join(STARTUP, LINK_NAME)


def pythonw():
    exe = sys.executable
    cand = os.path.join(os.path.dirname(exe), "pythonw.exe")
    if os.path.exists(cand):
        return cand
    if exe.lower().endswith("pythonw.exe"):
        return exe
    return exe


def build_vbs():
    lines = [
        "' Auto-start launcher for the Mechrevo charge-limit guard.",
        "' Generated by install_autostart.py -- do not edit by hand.",
        "Set sh = CreateObject(\"WScript.Shell\")",
        'sh.CurrentDirectory = "%s"' % HERE,
        'sh.Run """%s"" ""%s""", 0, False' % (pythonw(), GUARD),
    ]
    return "\r\n".join(lines) + "\r\n"


def install():
    if not os.path.exists(GUARD):
        print("ERROR: pin_guard.py not found next to this script:", GUARD)
        return 1
    os.makedirs(STARTUP, exist_ok=True)
    with open(LINK_PATH, "w", encoding="ascii", newline="") as f:
        f.write(build_vbs())
    print("installed ->", LINK_PATH)
    print("  pythonw :", pythonw())
    print("  guard   :", GUARD)
    return 0


def remove():
    if os.path.exists(LINK_PATH):
        os.remove(LINK_PATH)
        print("removed ->", LINK_PATH)
    else:
        print("nothing to remove (", LINK_PATH, "not found )")
    return 0


def start_now():
    try:
        subprocess.Popen([pythonw(), GUARD], cwd=HERE,
                         stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                         creationflags=0x00000008 | 0x08000000)  # DETACHED | NO_WINDOW
        print("guard started in background")
        return True
    except Exception as exc:
        print("failed to start guard:", exc)
        return False


def status():
    print("startup file :", LINK_PATH, "->", "EXISTS" if os.path.exists(LINK_PATH) else "MISSING")
    hb = os.path.join(HERE, "guard_heartbeat.json")
    if os.path.exists(hb):
        import json
        import time
        try:
            with open(hb, "r", encoding="utf-8") as f:
                d = json.load(f)
            age = time.time() - float(d.get("time", 0))
            print("heartbeat    : %s (%.0f s ago) enabled=%s limit=%s action=%s"
                  % (d.get("time_str"), age, d.get("enabled"), d.get("limit"), d.get("action")))
        except Exception as exc:
            print("heartbeat    : unreadable", exc)
    else:
        print("heartbeat    : none")
    return 0


if __name__ == "__main__":
    if "--remove" in sys.argv:
        sys.exit(remove())
    if "--status" in sys.argv:
        sys.exit(status())
    rc = install()
    if rc == 0:
        start_now()
        import time
        time.sleep(3)
        status()
    sys.exit(rc)
